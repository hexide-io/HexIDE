    public async Task MeasuredConversions(string function, string text, double expected, int error)
    {
        Func<Task> act = () => Run($"Debug.Print {function}(\"{text}\")\n");
        if (error != 0)
        {
            (await act.Should().ThrowAsync<VBRunTimeException>()).Which.Error.ErrNo.Should().Be(error);
            return;
        }
        await act();
        var value = function switch
        {
            "CInt" => new Vb6Value((int)expected),
            "CLng" => new Vb6Value((long)expected),
            "CByte" => new Vb6Value((byte)expected),
            "CSng" => new Vb6Value((float)expected),
            "CCur" => Vb6Value.NewCurrency((decimal)expected),
            "CDec" => Vb6Value.NewDecimal((decimal)expected),
            _ => new Vb6Value(expected)
        };
        AssertDebugLog([value]);
    }
