    [AvaloniaTheory]
    [MemberData(nameof(ThickRefusals))]
    public void Unimplemented_thick_pens_refuse_before_drawing_or_moving(string target, string statement)
    {
        var drawing = string.Join("\n", statement.Split('\n').Select(s => target + s));
        var run = RunLoad(Form, $"On Error Resume Next\n{target}ScaleMode = vbPixels\n{target}Cls\n"
            + $"{target}CurrentX = 7\n{target}CurrentY = 8\n" + drawing + "\nDebug.Print \"continued\"",
            window =>
            {
                Control owner = target == "" ? window : window.GetLogicalDescendants().OfType<VBPictureBox>().Single();
                RuntimeDrawing.TryGet(owner, "CurrentX", out var x).Should().BeTrue();
                RuntimeDrawing.TryGet(owner, "CurrentY", out var y).Should().BeTrue();
                x.Value.Should().Be(7f);
                y.Value.Should().Be(8f);
                var background = RuntimeDrawing.Call(owner, "Point", [new Vb6Value(2), new Vb6Value(2)]).Value;
                for (var row = 0; row < 80; row++)
                for (var column = 0; column < 80; column++)
                    RuntimeDrawing.Call(owner, "Point", [new Vb6Value(column), new Vb6Value(row)]).Value.Should().Be(background);
            });
        run.Errors.Should().ContainSingle().Which.Should().BeOfType<NotImplementedException>()
            .Which.Message.Should().Contain("#988");
        run.Printed.Should().BeEmpty();
    }
