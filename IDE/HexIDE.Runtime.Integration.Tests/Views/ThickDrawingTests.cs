    [AvaloniaTheory]
    [MemberData(nameof(ThickGrids))]
    public void Thick_points_and_circles_match_every_measured_pixel(string target, string statement, string position, string expected)
    {
        var lines = expected.ReplaceLineEndings("\n").Split('\n', StringSplitOptions.RemoveEmptyEntries);
        var earlierGrid = statement.Contains("(10, 10)");
        var left = earlierGrid ? (statement.StartsWith("DrawWidth = 5") ? 5 : 6) : 14;
        var right = earlierGrid ? (left == 5 ? 15 : 14) : 66;
        var top = earlierGrid ? int.Parse(lines[0].AsSpan(1, 3)) : 14;
        var bottom = earlierGrid ? int.Parse(lines[^1].AsSpan(1, 3)) : 66;
        var drawing = string.Join("\n", statement.Split(": ").Select(s => target + s));
        var form = Form.Replace("3195", "1800").Replace("4680", "1800");
        var run = RunLoad(form, $"{target}ScaleMode = vbPixels\n{target}AutoRedraw = True\n{target}Cls\n" + drawing + $"""

            Debug.Print CStr({target}CurrentX) & "|" & CStr({target}CurrentY)
            Dim x As Long, y As Long, row As String
            For y = {top} To {bottom}
                row = ""
                For x = {left} To {right}
                    If {target}Point(x, y) <> {target}Point(2, 2) Then
                        row = row & "#"
                    Else
                        row = row & "."
                    End If
                Next
                Debug.Print row
            Next
            """);
        run.Errors.Should().BeEmpty();
        var rows = Enumerable.Repeat(new string('.', right - left + 1), bottom - top + 1).ToArray();
        foreach (var line in lines)
            rows[int.Parse(line.AsSpan(1, 3)) - top] = line.Substring(5 + left, right - left + 1);
        run.Printed.Should().Equal(new[] { position }.Concat(rows));
    }

