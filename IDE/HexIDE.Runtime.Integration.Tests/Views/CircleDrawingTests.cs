    public void Circle_uses_method_colour_conversion_or_ForeColor(string target, string setup, string argument, string expected)
    {
        var run = RunLoad(Form, $"{target}ScaleMode = vbPixels\n" + (setup == "" ? "" : target + setup + "\n")
