    [AvaloniaTheory]
    [InlineData("-50")]
    [InlineData("10, , 7")]
    [InlineData("10, , -7")]
    [InlineData("10, , , 7")]
    [InlineData("10, , , -7")]
    public void Circle_errors_precede_any_drawing(string arguments)
    {
        var run = RunLoad(Form, $"""
            ScaleMode = vbPixels
            Dim background As Long
            background = Point(0, 0)
            On Error Resume Next
            Circle (40, 40), {arguments}
            Debug.Print CStr(Err.Number)
            Dim x As Long, y As Long, drawn As Long
            For y = 14 To 66
                For x = 14 To 66
                    If Point(x, y) <> background Then drawn = drawn + 1
                Next
            Next
            Debug.Print CStr(drawn)
            """);
        run.Errors.Should().BeEmpty();
        run.Printed.Should().Equal("5", "0");
    }

