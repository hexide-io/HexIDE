    [AvaloniaTheory]
    [MemberData(nameof(Grids))]
    public void Circle_matches_the_whole_measured_Point_grid(string target, string statement, string expected)
    {
        var draw = string.Join("\n", statement.Split(": ").Select(s => target + s));
        var run = RunLoad(Form, $"""
            {target}AutoRedraw = True
            {target}ScaleMode = vbPixels
            {target}DrawWidth = 1
            {target}FillStyle = 1
            {target}FillColor = 0
            {target}Cls
            Dim background As Long
            background = {target}Point(0, 0)
            {draw}
            Dim x As Long, y As Long, c As Long, row As String
            For y = 14 To 66
                row = ""
                For x = 14 To 66
                    c = {target}Point(x, y)
                    If c = background Then
                        row = row & "."
                    ElseIf c = vbRed Then
                        row = row & "R"
                    ElseIf c = vbGreen Then
                        row = row & "G"
                    Else
                        row = row & "#"
                    End If
                Next
                Debug.Print row
            Next
            Debug.Print CStr({target}CurrentX) & "|" & CStr({target}CurrentY)
            """);
        run.Errors.Should().BeEmpty();
        var rows = Enumerable.Repeat(new string('.', 53), 53).ToArray();
        foreach (var line in expected.ReplaceLineEndings("\n").Split('\n', StringSplitOptions.RemoveEmptyEntries))
            rows[int.Parse(line.AsSpan(1, 3)) - 14] = line[5..];
        run.Printed.Take(53).Should().Equal(rows);
        run.Printed.Last().Should().Be(statement.Contains("40.5") ? "40.53333|40.53333" : "40|40");
    }

